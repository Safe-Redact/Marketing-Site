import { readFileSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import YAML from "yaml";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "..");
const templatePath = path.join(repositoryRoot, "config", "decap-cms.yml");
const defaultOutputPath = path.join(repositoryRoot, "public", "admin", "config.yml");
const disabledOrigin = "https://cms-auth.invalid";
const disabledSiteOrigin = "https://site.invalid";

const repositoryPattern = /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/;
const branchPattern = /^[A-Za-z0-9](?:[A-Za-z0-9._/-]*[A-Za-z0-9])?$/;
const endpointPattern = /^[A-Za-z0-9](?:[A-Za-z0-9/_-]*[A-Za-z0-9])?$/;

function enabled(value) {
  return /^(?:1|true)$/i.test(value ?? "");
}

function required(environment, name) {
  const value = environment[name]?.trim();
  if (!value) {
    throw new Error(`Invalid CMS configuration: ${name} is required when CMS_ENABLED is true.`);
  }
  return value;
}

function origin(name, value) {
  let parsed;
  try {
    parsed = new URL(value);
  } catch {
    throw new Error(`Invalid CMS configuration: ${name} must be an absolute HTTPS origin.`);
  }

  if (
    parsed.protocol !== "https:" ||
    parsed.username ||
    parsed.password ||
    parsed.pathname !== "/" ||
    parsed.search ||
    parsed.hash ||
    parsed.hostname.includes("*")
  ) {
    throw new Error(`Invalid CMS configuration: ${name} must be a credential-free HTTPS origin.`);
  }

  return parsed.origin;
}

function endpoint(value) {
  if (!endpointPattern.test(value) || value.includes("//") || value.includes("..")) {
    throw new Error("Invalid CMS configuration: CMS_OAUTH_AUTH_ENDPOINT must be a relative path.");
  }
  return value;
}

function repository(value) {
  if (!repositoryPattern.test(value)) {
    throw new Error("Invalid CMS configuration: CMS_GITHUB_REPOSITORY must use owner/repository form.");
  }
  return value;
}

function branch(value) {
  if (
    !branchPattern.test(value) ||
    value.includes("..") ||
    value.includes("//") ||
    value.includes("@{") ||
    value.endsWith(".lock")
  ) {
    throw new Error("Invalid CMS configuration: CMS_PUBLISH_BRANCH is not a safe Git branch name.");
  }
  return value;
}

function scope(value) {
  if (value !== "public_repo") {
    throw new Error(
      "Invalid CMS configuration: CMS_AUTH_SCOPE must remain public_repo until a repository visibility review."
    );
  }
  return value;
}

export function resolveCmsSettings(environment = {}) {
  if (!enabled(environment.CMS_ENABLED)) {
    return {
      enabled: false,
      siteOrigin: disabledSiteOrigin,
      oauthBaseUrl: disabledOrigin,
      authEndpoint: "auth",
      repository: "Safe-Redact/Marketing-Site",
      publishBranch: "master",
      authScope: "public_repo",
    };
  }

  return {
    enabled: true,
    siteOrigin: origin("PUBLIC_SITE_ORIGIN", required(environment, "PUBLIC_SITE_ORIGIN")),
    oauthBaseUrl: origin(
      "CMS_OAUTH_PUBLIC_BASE_URL",
      required(environment, "CMS_OAUTH_PUBLIC_BASE_URL")
    ),
    authEndpoint: endpoint(environment.CMS_OAUTH_AUTH_ENDPOINT?.trim() || "auth"),
    repository: repository(required(environment, "CMS_GITHUB_REPOSITORY")),
    publishBranch: branch(required(environment, "CMS_PUBLISH_BRANCH")),
    authScope: scope(environment.CMS_AUTH_SCOPE?.trim() || "public_repo"),
  };
}

export function buildCmsConfig(environment = {}) {
  const template = YAML.parse(readFileSync(templatePath, "utf8"));
  const settings = resolveCmsSettings(environment);
  const site = new URL(settings.siteOrigin);

  template.backend = {
    ...template.backend,
    repo: settings.repository,
    branch: settings.publishBranch,
    base_url: settings.oauthBaseUrl,
    auth_endpoint: settings.authEndpoint,
    auth_scope: settings.authScope,
    site_domain: site.host,
  };
  template.site_url = settings.siteOrigin;
  template.display_url = settings.siteOrigin;
  template.logo_url = `${settings.siteOrigin}/favicon.svg`;

  const status = settings.enabled
    ? "CMS authentication enabled with public deployment coordinates."
    : "CMS authentication disabled: reserved non-routable origins prevent provider fallback.";

  return `# Generated by scripts/render-cms-config.mjs. Public configuration; never add secrets.\n# ${status}\n${YAML.stringify(template)}`;
}

export async function writeCmsConfig(environment = process.env, outputPath = defaultOutputPath) {
  const config = await buildCmsConfig(environment);
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, config, "utf8");
  return outputPath;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    // --disabled renders the fail-closed profile from a fixed environment, so test
    // and CI renders never depend on a developer's .env.local or exported shell values.
    const forceDisabled = process.argv.slice(2).includes("--disabled");
    const environment = forceDisabled ? { CMS_ENABLED: "false" } : process.env;
    const outputPath = await writeCmsConfig(environment);
    const profile = forceDisabled ? "disabled profile" : "deployment profile";
    console.log(
      `Generated public Decap configuration (${profile}): ${path.relative(repositoryRoot, outputPath)}`
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
